-- TrueWage schema for Supabase / Postgres.
-- The app creates all of this by itself on start-up (python server.py), so you do not have to run it.
-- It is here so you can read it, or run it by hand in the Supabase SQL editor.
-- Tables live in their own schema ("truewage"), which Supabase does not expose through its public REST API,
-- and Row Level Security is enabled on every table so the public anon key cannot read or write anything.

CREATE SCHEMA IF NOT EXISTS truewage;
SET search_path TO truewage;

CREATE TABLE IF NOT EXISTS users(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, phone TEXT UNIQUE NOT NULL, name TEXT NOT NULL, pw TEXT NOT NULL, lang TEXT NOT NULL DEFAULT 'en', created BIGINT NOT NULL);

CREATE TABLE IF NOT EXISTS sessions(token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, expires BIGINT NOT NULL);

CREATE TABLE IF NOT EXISTS userdata(user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE, json TEXT NOT NULL, version BIGINT NOT NULL DEFAULT 0, updated BIGINT NOT NULL);

CREATE TABLE IF NOT EXISTS work_sessions(user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, sid TEXT NOT NULL, date TEXT NOT NULL, platform TEXT, zone TEXT, online_min DOUBLE PRECISION, bonus DOUBLE PRECISION, source TEXT, n_orders BIGINT, pay DOUBLE PRECISION, incentive DOUBLE PRECISION, deduction DOUBLE PRECISION, km DOUBLE PRECISION, PRIMARY KEY(user_id, sid));

CREATE TABLE IF NOT EXISTS orders(user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, sid TEXT NOT NULL, idx BIGINT NOT NULL, hour DOUBLE PRECISION, zone TEXT, km DOUBLE PRECISION, pay DOUBLE PRECISION, incentive DOUBLE PRECISION, deduction DOUBLE PRECISION, dur_min DOUBLE PRECISION, PRIMARY KEY(user_id, sid, idx));

CREATE TABLE IF NOT EXISTS shifts(user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, sid TEXT NOT NULL, date TEXT, platform TEXT, start_ts DOUBLE PRECISION, end_ts DOUBLE PRECISION, online_min DOUBLE PRECISION, km DOUBLE PRECISION, gps TEXT, zone TEXT, zone_min TEXT, PRIMARY KEY(user_id, sid));

CREATE TABLE IF NOT EXISTS expenses(user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, eid TEXT NOT NULL, date TEXT NOT NULL, category TEXT, amount DOUBLE PRECISION, litres DOUBLE PRECISION, odo DOUBLE PRECISION, note TEXT, PRIMARY KEY(user_id, eid));

CREATE TABLE IF NOT EXISTS imports(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, ts BIGINT NOT NULL, reader TEXT, images BIGINT, cached BIGINT, sent BIGINT, sessions BIGINT, orders BIGINT, models TEXT);

CREATE TABLE IF NOT EXISTS statements(user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, sid TEXT NOT NULL, ts BIGINT NOT NULL, period_from TEXT, period_to TEXT, monthly_take_home DOUBLE PRECISION, PRIMARY KEY(user_id, sid));

CREATE TABLE IF NOT EXISTS events(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, ts BIGINT NOT NULL, kind TEXT NOT NULL, detail TEXT);

CREATE TABLE IF NOT EXISTS ai_usage(user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, day TEXT NOT NULL, images BIGINT NOT NULL DEFAULT 0, asks BIGINT NOT NULL DEFAULT 0, PRIMARY KEY(user_id, day));

CREATE TABLE IF NOT EXISTS registry(id TEXT PRIMARY KEY, hash TEXT NOT NULL, data TEXT, created TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS contributions(rider TEXT PRIMARY KEY, cells TEXT NOT NULL, ts BIGINT NOT NULL);

CREATE TABLE IF NOT EXISTS extract_cache(key TEXT PRIMARY KEY, screens TEXT NOT NULL, ts BIGINT NOT NULL);

CREATE TABLE IF NOT EXISTS ai_budget(day TEXT PRIMARY KEY, images BIGINT NOT NULL DEFAULT 0);

CREATE TABLE IF NOT EXISTS kv(k TEXT PRIMARY KEY, v TEXT NOT NULL);

CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);
CREATE INDEX IF NOT EXISTS ws_date ON work_sessions(user_id, date);
CREATE INDEX IF NOT EXISTS ord_zone ON orders(user_id, zone);
CREATE INDEX IF NOT EXISTS exp_date ON expenses(user_id, date);
CREATE INDEX IF NOT EXISTS ev_user ON events(user_id, ts);
CREATE INDEX IF NOT EXISTS imp_user ON imports(user_id, id);
CREATE INDEX IF NOT EXISTS cache_ts ON extract_cache(ts);

ALTER TABLE truewage.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE truewage.sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE truewage.userdata ENABLE ROW LEVEL SECURITY;
ALTER TABLE truewage.work_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE truewage.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE truewage.shifts ENABLE ROW LEVEL SECURITY;
ALTER TABLE truewage.expenses ENABLE ROW LEVEL SECURITY;
ALTER TABLE truewage.imports ENABLE ROW LEVEL SECURITY;
ALTER TABLE truewage.statements ENABLE ROW LEVEL SECURITY;
ALTER TABLE truewage.events ENABLE ROW LEVEL SECURITY;
ALTER TABLE truewage.ai_usage ENABLE ROW LEVEL SECURITY;
ALTER TABLE truewage.registry ENABLE ROW LEVEL SECURITY;
ALTER TABLE truewage.contributions ENABLE ROW LEVEL SECURITY;
ALTER TABLE truewage.extract_cache ENABLE ROW LEVEL SECURITY;
ALTER TABLE truewage.ai_budget ENABLE ROW LEVEL SECURITY;
ALTER TABLE truewage.kv ENABLE ROW LEVEL SECURITY;

DO $$ BEGIN
  REVOKE ALL ON SCHEMA truewage FROM anon, authenticated;
  REVOKE ALL ON ALL TABLES IN SCHEMA truewage FROM anon, authenticated;
EXCEPTION WHEN undefined_object THEN NULL;
END $$;
